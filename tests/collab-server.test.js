import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { createCollabServer } from '../server/collab.mjs';

test('collaboration lifecycle enforces owner/editor/viewer, versions, persistence and Studio sync',async t=>{
  const root=mkdtempSync(join(tmpdir(),'luauforge-collab-')),dataFile=join(root,'workspaces.json');
  t.after(()=>rmSync(root,{recursive:true,force:true}));
  const allowed='https://sillydev2026.github.io';
  let collab=createCollabServer({dataFile,allowedOrigins:[allowed]});
  await new Promise(resolve=>collab.server.listen(0,'127.0.0.1',resolve));
  let url='http://127.0.0.1:'+collab.server.address().port;
  t.after(async()=>{if(collab.server.listening)await collab.close();});
  async function request(path,method='GET',body,token,origin=allowed){
    const response=await fetch(url+path,{method,headers:{...(origin?{Origin:origin}:{}),...(token?{Authorization:'Bearer '+token}:{}),...(body?{'Content-Type':'application/json'}:{})},...(body?{body:JSON.stringify(body)}:{})});
    return {status:response.status,headers:response.headers,json:await response.json()};
  }
  assert.equal((await request('/health')).json.ok,true);
  assert.equal((await request('/api/workspaces','POST',{name:'Big Game',memberName:'Owner'},null,'https://random.example')).status,403);
  const created=await request('/api/workspaces','POST',{name:'Big Game',memberName:'Owner'});
  assert.equal(created.status,201);
  const workspaceId=created.json.workspace.id,owner=created.json.token;
  assert.ok(owner.length>=30);
  assert.equal(created.json.workspace.role,'owner');
  const workspacePath='/api/workspaces/'+workspaceId;
  assert.equal((await request(workspacePath)).status,401);
  assert.equal((await request(workspacePath,'GET',null,'invalidtoken')).status,401);
  assert.equal((await request(workspacePath,'GET',null,owner)).status,200);
  assert.equal((await request(workspacePath,'GET',null,owner)).json.workspace.name,'Big Game');
  const badInvite=await request(workspacePath+'/invites','POST',{role:'owner'},owner);
  assert.equal(badInvite.status,400);
  const invited=await request(workspacePath+'/invites','POST',{role:'editor'},owner);
  assert.equal(invited.status,201);
  assert.ok(invited.json.code.length>=30);
  const joined=await request('/api/join','POST',{code:invited.json.code,memberName:'Contributor'});
  assert.equal(joined.status,200);
  assert.equal(joined.json.workspace.role,'editor');
  const writer=joined.json.token;
  assert.equal((await request('/api/join','POST',{code:invited.json.code,memberName:'Another'})).status,404);
  const viewerInvite=await request(workspacePath+'/invites','POST',{role:'viewer'},owner);
  const readOnly=await request('/api/join','POST',{code:viewerInvite.json.code,memberName:'Observer'});
  assert.equal(readOnly.status,200);
  assert.equal(readOnly.json.workspace.role,'viewer');
  const viewer=readOnly.json.token;
  assert.equal((await request(workspacePath+'/invites','POST',{role:'editor'},writer)).status,403);
  assert.equal((await request(workspacePath+'/studio-token','POST',{},writer)).status,403);
  assert.equal((await request(workspacePath+'/scripts','POST',{name:'Main',type:'Script',target:'ServerScriptService'},viewer)).status,403);
  const source='local PlayersData = {}\nreturn PlayersData';
  const script=await request(workspacePath+'/scripts','POST',{name:'PlayersData',type:'ModuleScript',target:'ReplicatedStorage',source},writer);
  assert.equal(script.status,201);
  assert.equal(script.json.script.version,1);
  const scriptId=script.json.script.id;
  assert.deepEqual(Object.keys(script.json.script).sort(),['id','name','source','target','type','updatedAt','updatedBy','version'].sort());
  assert.equal((await request(workspacePath+'/scripts','POST',{name:'PlayersData',type:'Script',target:'ReplicatedStorage'},writer)).status,409);
  assert.equal((await request(workspacePath+'/scripts','POST',{name:'../../bad',type:'Script',target:'ServerScriptService'},writer)).status,400);
  assert.equal((await request(workspacePath+'/scripts','POST',{name:'Other',type:'ServerScript',target:'ServerScriptService'},writer)).status,400);
  assert.equal((await request(workspacePath+'/scripts','POST',{name:'Other',type:'Script',target:'Workspace'},writer)).status,400);
  assert.equal((await request(workspacePath+'/scripts','GET',null,viewer)).json.scripts[0].name,'PlayersData');
  assert.equal((await request(workspacePath+'/scripts/'+scriptId,'GET',null,viewer)).json.script.source,source);
  const edited=await request(workspacePath+'/scripts/'+scriptId,'PATCH',{version:1,source:'return {Ready=true}',type:'ModuleScript',target:'StarterGui'},writer);
  assert.equal(edited.status,200);
  assert.equal(edited.json.script.version,2);
  assert.equal(edited.json.script.target,'StarterGui');
  assert.equal((await request(workspacePath+'/scripts/'+scriptId,'PATCH',{version:1,source:'bad'},owner)).status,409);
  assert.equal((await request(workspacePath+'/scripts/'+scriptId,'PATCH',{version:2,source:'bad'},viewer)).status,403);
  const pair=await request(workspacePath+'/studio-token','POST',{},owner);
  assert.equal(pair.status,201);
  const studioToken=pair.json.token;
  assert.ok(!JSON.stringify((await request(workspacePath,'GET',null,viewer)).json).includes(studioToken));
  assert.equal((await request('/api/studio/'+workspaceId+'/changes','GET',null,writer)).status,401);
  const pending=await request('/api/studio/'+workspaceId+'/changes','GET',null,studioToken);
  assert.equal(pending.status,200);
  assert.equal(pending.json.changes.length,1);
  assert.equal(pending.json.changes[0].target,'StarterGui');
  assert.equal(pending.json.changes[0].source,'return {Ready=true}');
  assert.equal((await request('/api/studio/'+workspaceId+'/ack','POST',{scriptId,version:1,success:true},studioToken)).status,409);
  assert.equal((await request('/api/studio/'+workspaceId+'/ack','POST',{scriptId,version:2,success:true},studioToken)).status,200);
  assert.equal((await request('/api/studio/'+workspaceId+'/changes','GET',null,studioToken)).json.changes.length,0);
  const status=await request(workspacePath+'/studio-status','GET',null,viewer);
  assert.equal(status.json.studio.pending,0);
  assert.equal(status.json.studio.applied,1);
  const next=await request(workspacePath+'/scripts/'+scriptId,'PATCH',{version:2,source:'print("revision 3")'},owner);
  assert.equal(next.json.script.version,3);
  assert.equal((await request('/api/studio/'+workspaceId+'/changes','GET',null,studioToken)).json.changes.length,1);
  const secondPair=await request(workspacePath+'/studio-token','POST',{},owner);
  assert.equal((await request('/api/studio/'+workspaceId+'/changes','GET',null,studioToken)).status,401);
  assert.equal((await request('/api/studio/'+workspaceId+'/changes','GET',null,secondPair.json.token)).json.changes.length,1);
  const saved=JSON.parse(readFileSync(dataFile,'utf8'));
  assert.ok(!JSON.stringify(saved).includes(owner));
  assert.ok(!JSON.stringify(saved).includes(writer));
  assert.ok(!JSON.stringify(saved).includes(secondPair.json.token));
  await collab.close();
  collab=createCollabServer({dataFile,allowedOrigins:[allowed]});
  await new Promise(resolve=>collab.server.listen(0,'127.0.0.1',resolve));
  url='http://127.0.0.1:'+collab.server.address().port;
  assert.equal((await request(workspacePath+'/scripts/'+scriptId,'GET',null,owner)).json.script.version,3);
  assert.equal((await request('/api/studio/'+workspaceId+'/changes','GET',null,secondPair.json.token)).json.changes.length,1);
});

test('studio plugin restricts writes to designated roots and tagged script instances',async()=>{
  const {readFile}=await import('node:fs/promises');
  const source=await readFile(new URL('../studio/LuauForgeBridge.plugin.lua',import.meta.url),'utf8');
  for(const target of ['ReplicatedStorage','ServerScriptService','StarterGui','StarterPlayerScripts'])assert.match(source,new RegExp(target));
  assert.match(source,/ScriptEditorService:UpdateSourceAsync/);
  assert.match(source,/GetAttribute\("LuauForgeScriptId"\)/);
  assert.match(source,/GetAttribute\("LuauForgeWorkspace"\)/);
  assert.match(source,/if RunService:IsRunning\(\)/);
  assert.match(source,/refusing to overwrite/);
  assert.doesNotMatch(source,/loadstring\s*\(/);
});

test('GitHub Pages UI never embeds private Studio pairing or workspace tokens',async()=>{
  const {readFile}=await import('node:fs/promises');
  const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
  const js=await readFile(new URL('../src/collab.js',import.meta.url),'utf8');
  assert.match(html,/id="collab-settings"/);
  assert.match(html,/id="collab-type"/);
  assert.match(html,/id="collab-target"/);
  assert.match(html,/id="collab-save-script"/);
  assert.match(js,/sessionStorage/);
  assert.match(js,/version:entry.version/);
  assert.match(js,/collab\/'/);
  assert.doesNotMatch(js,/localStorage\.setItem\([^)]*token/);
});
